// Sticker sounds with ElevenLabs Sound Effects: every rare and special sticker has a short sound of its own (SPEC 3.6, 3.7)
//   -> web/audio/sfx/<set>-<word>.mp3 and the module web/js/gen/sfx.js (which stickers have a sound).
// The prompts live with the stickers, in STICKER_FX of web/js/data.js; a sticker without a file is simply silent.
// Run: node app/sfx.js                    (skips sounds that already exist)
//      node app/sfx.js --force            (render everything again)
//      node app/sfx.js --only farm:dog    (one sticker, e.g. after changing its prompt; implies --force for it)
//      node app/sfx.js --list             (only print what has no file yet; no API calls)
// The API key is read from ELEVENLABS_API_KEY or from the .env file in ENV_FILE, like app/voice.js (never stored here).
const fs = require('fs'), path = require('path'), { pathToFileURL } = require('url');
const ROOT = path.join(__dirname, '..');
const WEB = path.join(ROOT, 'web');
const OUT = path.join(WEB, 'audio', 'sfx');
const GEN = path.join(WEB, 'js', 'gen', 'sfx.js');
const ENV_FILE = process.env.ENV_FILE || 'C:/Users/User/Documents/Projects/EgzaminPolskiB1/.env';
const FORCE = process.argv.includes('--force');
const LIST = process.argv.includes('--list');
const ONLY = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : null;
const SECONDS = 1.5;          // SPEC 3.7: up to 1.5 s, one sound per sticker
const INFLUENCE = 0.6;        // how literally the prompt is followed (0..1)

function apiKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY;
  const m = fs.readFileSync(ENV_FILE, 'utf8').match(/^elevenlabs_api_key=(.+)$/im);
  if (!m) throw new Error('no elevenlabs_api_key in ' + ENV_FILE);
  return m[1].trim().replace(/^"|"$/g, '');
}
// the same name the app builds: "farm:dog" -> farm-dog.mp3, "toys:nesting dolls" -> toys-nesting-dolls.mp3
const file = key => key.toLowerCase().replace(/[^a-z0-9]+/g, '-') + '.mp3';
async function sound(text) {
  const r = await fetch('https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_64', {
    method: 'POST', headers: { 'xi-api-key': apiKey(), 'Content-Type': 'application/json' },
    body: JSON.stringify({ text, duration_seconds: SECONDS, prompt_influence: INFLUENCE }),
  });
  if (!r.ok) throw new Error(`${r.status} ${await r.text()}`);
  return Buffer.from(await r.arrayBuffer());
}
(async () => {
  const { STICKER_FX, STICKERS } = await import(pathToFileURL(path.join(WEB, 'js', 'data.js')).href);
  const all = Object.entries(STICKER_FX).filter(([, fx]) => fx.snd);
  const unknown = all.filter(([k]) => !STICKERS[k]).map(([k]) => k);
  if (unknown.length) throw new Error('STICKER_FX names stickers that do not exist: ' + unknown.join(', '));
  fs.mkdirSync(OUT, { recursive: true });
  const todo = all.filter(([k]) => ONLY ? k === ONLY : FORCE || !fs.existsSync(path.join(OUT, file(k))));
  console.log(`${all.length} sticker sounds, ${todo.length} to render`);
  if (LIST) { todo.forEach(([k, fx]) => console.log(k, '—', fx.snd)); return; }
  let made = 0, failed = 0;
  for (const [k, fx] of todo) {
    try { fs.writeFileSync(path.join(OUT, file(k)), await sound(fx.snd)); made++; console.log(k); }
    catch (e) { failed++; console.error('FAILED', k, e.message.slice(0, 200)); }
  }
  const have = all.map(([k]) => k).filter(k => fs.existsSync(path.join(OUT, file(k))));
  fs.writeFileSync(GEN, `// Generated by app/sfx.js: stickers that have a sound (audio/sfx/<set>-<word>.mp3). Do not edit by hand.\nexport const SFX = ${JSON.stringify(have)};\n`);
  console.log(`made ${made}, failed ${failed}, ${have.length} of ${all.length} stickers have a sound`);
})();
